/* Service worker — met l'application en cache pour qu'elle marche hors ligne,
   tout en allant chercher la dernière version dès qu'il y a du réseau. */

const CACHE_NAME = "cours-maths-v2";
const FILES_TO_CACHE = [
  "./",
  "./index.html",
  "./manifest.json",
  "./icon-192.png",
  "./icon-512.png",
  "./programme-7eme-numerique.pdf",
  "./programme-7eme-geometrie.pdf",
  "./programme-8eme-numerique.pdf",
  "./programme-8eme-geometrie.pdf",
  "./programme-9eme-numerique.pdf",
  "./programme-9eme-geometrie.pdf"
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(FILES_TO_CACHE))
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
      )
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  event.respondWith(
    fetch(event.request)
      .then((response) => {
        if (response && response.status === 200 && event.request.method === "GET") {
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
        }
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});
